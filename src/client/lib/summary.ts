// lib/summary.ts — Build a markdown copy summary from a report
import type { InvestigationReport } from './types.js';
import { shortHash, relativeTime } from './format.js';
import { txStatusLabel, causalityLabel } from './status.js';

export function buildMarkdownSummary(report: InvestigationReport): string {
  const lines: string[] = [];
  lines.push(`# RevertLens Investigation Summary`);
  lines.push('');
  lines.push(`**Transaction:** ${shortHash(report.txHash)} ([Celoscan](https://celoscan.io/tx/${report.txHash}))`);
  lines.push(`**Status:** ${txStatusLabel(report.status)}`);
  if (report.diagnosis.causalityCategory) {
    lines.push(`**Causality:** ${causalityLabel(report.diagnosis.causalityCategory)}`);
  }
  lines.push(`**Investigated:** ${relativeTime(report.createdAt)}`);
  lines.push('');
  lines.push(`## Headline`);
  lines.push(report.diagnosis.headline);
  lines.push('');
  lines.push(`## Narrative`);
  lines.push(report.diagnosis.narrative);
  if (report.diagnosis.provenFacts.length > 0) {
    lines.push('');
    lines.push(`## Proven Facts`);
    report.diagnosis.provenFacts.forEach(f => lines.push(`- ${f}`));
  }
  if (report.diagnosis.likelyExplanations.length > 0) {
    lines.push('');
    lines.push(`## Likely Explanations`);
    report.diagnosis.likelyExplanations.forEach(e => lines.push(`- ${e}`));
  }
  if (report.diagnosis.safeNextSteps.length > 0) {
    lines.push('');
    lines.push(`## Safe Next Steps`);
    report.diagnosis.safeNextSteps.forEach(s => lines.push(`- ${s}`));
  }
  lines.push('');
  lines.push(`---`);
  lines.push(`*Generated by RevertLens — deterministic Celo transaction forensics*`);
  return lines.join('\n');
}
